// Builds docs/js/domain.js from the curated Markdown pages in docs/domain/.
//
//   node scripts/dev/build-domain.js          # write docs/js/domain.js
//   node scripts/dev/build-domain.js --check  # fail if it is stale or unsafe
//
// Why generate instead of hand-writing the data file: the Markdown is the thing
// a human reviews and git diffs, and the page has to work from file:// with no
// fetch. Duplicating the content by hand would guarantee the two drift, so one
// is derived from the other and --check proves it.
//
// The build REFUSES to publish a block that has no `source::` line or no
// `verified::` date. That is decision 5 in docs/assistant/DECISIONS.md enforced
// in code rather than trusted to discipline.
"use strict";

const fs = require("fs");
const path = require("path");

const REPO = path.resolve(__dirname, "..", "..");
const SRC_DIR = path.join(REPO, "docs", "domain");
const OUT = path.join(REPO, "docs", "js", "domain.js");
const CHECK = process.argv.includes("--check");

const problems = [];

function field(line, name) {
  const m = line.match(new RegExp("^" + name + "::\\s*(.*)$"));
  return m ? m[1].trim() : null;
}

function parsePage(file) {
  const raw = fs.readFileSync(path.join(SRC_DIR, file), "utf8");
  const lines = raw.split(/\r?\n/);
  const page = { file: file, title: "", tags: [], blocks: [] };
  let block = null;

  for (const line of lines) {
    if (/^#\s+/.test(line) && !page.title) {
      page.title = line.replace(/^#\s+/, "").trim();
      continue;
    }
    const tags = field(line, "tags");
    if (tags !== null) {
      page.tags = tags.split(",").map((t) => t.trim().toLowerCase()).filter(Boolean);
      continue;
    }
    if (/^##\s+/.test(line)) {
      if (block) page.blocks.push(block);
      block = { heading: line.replace(/^##\s+/, "").trim(), text: [], source: "", verified: "" };
      continue;
    }
    if (!block) continue;

    const src = field(line, "source");
    if (src !== null) { block.source = src; continue; }
    const ver = field(line, "verified");
    if (ver !== null) { block.verified = ver; continue; }
    block.text.push(line);
  }
  if (block) page.blocks.push(block);

  for (const b of page.blocks) {
    b.text = b.text.join(" ").replace(/\s+/g, " ").trim();
  }
  return page;
}

function validate(page) {
  const where = page.file;
  if (!page.title) problems.push(where + ": no page title (# heading)");
  if (!page.tags.length) problems.push(where + ": no tags:: line");
  if (!page.blocks.length) problems.push(where + ": no ## blocks");

  page.blocks.forEach((b, i) => {
    const at = where + " block " + (i + 1) + ' ("' + b.heading + '")';
    if (!b.text || b.text.length < 40) problems.push(at + ": text is empty or too short");
    if (!b.source) problems.push(at + ": no source:: line");
    if (!b.verified) problems.push(at + ": no verified:: line");
    if (b.verified && !/^\d{4}-\d{2}-\d{2}$/.test(b.verified)) {
      problems.push(at + ": verified must be YYYY-MM-DD, got " + b.verified);
    }
  });
}

function build() {
  const files = fs.existsSync(SRC_DIR)
    ? fs.readdirSync(SRC_DIR).filter((f) => f.endsWith(".md")).sort()
    : [];

  const pages = files.map(parsePage);
  pages.forEach(validate);

  /* Every block becomes one retrievable chunk. The heading and page title are
     prepended so the BM25 sees the topic words, not just the prose. */
  const chunks = [];
  for (const page of pages) {
    for (const b of page.blocks) {
      chunks.push({
        id: page.file.replace(/\.md$/, "") + "-" + chunks.length,
        page: page.title,
        heading: b.heading,
        tags: page.tags,
        text: b.heading + ". " + b.text,
        source: b.source,
        verified: b.verified,
        /* Corrections must be labelled as corrections at every surface (decision
           4: shown and named, never folded silently into the prose). */
        correction: /^corrections/i.test(page.file),
        unverified: /^not from a source/i.test(b.source)
      });
    }
  }

  const json = JSON.stringify({ pages: pages.map((p) => ({ title: p.title, file: p.file })), chunks: chunks }, null, 2);
  if (json.includes("</script")) {
    problems.push("domain content contains a </script sequence; it cannot be inlined verbatim");
  }

  const out =
    "/* GENERATED by scripts/dev/build-domain.js from docs/domain/*.md - do not edit.\n" +
    "   Run `node scripts/dev/build-domain.js` after changing a page, and\n" +
    "   `node scripts/dev/build-domain.js --check` to prove it is current. */\n" +
    "window.GUIDE_DOMAIN = " + json + ";\n";

  return { out: out, pages: pages.length, chunks: chunks.length };
}

const result = build();

if (problems.length) {
  console.log("FAIL " + problems.length + " problem(s) in docs/domain/:");
  problems.forEach((p) => console.log("  - " + p));
  process.exit(1);
}

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  /* Git checks this file out with CRLF on Windows (core.autocrlf=true), while
     this script writes LF. Compare newline-normalised, or every fresh clone
     would report the generated file as stale when it is identical. */
  const norm = (s) => s.replace(/\r\n/g, "\n");
  if (norm(current) !== norm(result.out)) {
    console.log("FAIL docs/js/domain.js is stale — run: node scripts/dev/build-domain.js");
    process.exit(1);
  }
  console.log("PASS domain pack is current (" + result.pages + " pages, " + result.chunks + " sourced blocks)");
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, result.out, "utf8");
console.log("wrote docs/js/domain.js: " + result.pages + " pages, " + result.chunks + " blocks");
